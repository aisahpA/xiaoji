export type MessageKey = keyof typeof strings;
export type Locale = 'zh' | 'en';

export function resolveLanguage(language: Language, hostLanguage: string): Locale {
  return language === 'auto' ? hostLanguage.toLowerCase().startsWith('zh') ? 'zh' : 'en' : language;
}

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  const message = strings[key][locale === 'zh' ? 0 : 1];
  return message.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? '{' + name + '}'));
}

export function isMessageKey(value: string): value is MessageKey { return value in strings; }
